import { webkit, devices } from "@playwright/test";
const out = "docs/design/tabel-mobile";
const b = await webkit.launch();
const ctx = await b.newContext({ ...devices["iPhone 13"], colorScheme: "dark" });
const p = await ctx.newPage();
const errors: string[] = [];
p.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await p.addInitScript(() => localStorage.setItem("neeklo-fieldops-theme", "dark"));
await p.goto("http://localhost:5273/gas/tabel");
await p.getByRole("button", { name: "Открыть как таблицу" }).click({ timeout: 60000 });
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/after-1-table.png` });
await p.getByRole("button", { name: "Во весь экран" }).click();
const g = p.getByRole("grid").first();
await g.locator('td[role="gridcell"]').filter({ hasText: "₽" }).first().tap();
await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/after-2-fullscreen-sum.png` });
await g.locator('th[role="columnheader"][data-col="1"]').tap();
await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/after-3-column-sum.png` });
await p.getByRole("button", { name: "Свернуть" }).click();
await p.getByRole("button", { name: /^Вид и фильтры/ }).click();
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/after-4-settings.png` });
await p.reload();
await p.waitForTimeout(4000);
console.log("table after reload:", await p.getByRole("grid").count(), "console errors:", errors.length, errors.slice(0,3));
await b.close();
