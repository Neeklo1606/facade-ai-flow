import type { EmailTemplate } from "@/contracts";

/**
 * Встроенный шаблон письма запроса (ADR-025, поправка от 26.09.2026).
 *
 * Шаблоны письма жили только в фикстурах демонстрации, и на чистой базе заказчика шаг «Письмо»
 * в мастере запроса не заполнялся: первая цепочка обрывалась на последнем шаге. Текст письма —
 * наш, а не данные заказчика, поэтому его место в коде продукта. Шаблоны заказчика, когда
 * появятся, встанут в списке первыми.
 */
export const DEFAULT_RFQ_TEMPLATE: EmailTemplate = {
  id: "tpl-default",
  name: "Запрос цены и срока",
  subject: "Запрос цены: {объект}, {позиций} поз.",
  body: "Добрый день, {контакт}!\n\nПросим направить коммерческое предложение на материалы для объекта {объект} ({регион}). Перечень позиций во вложении.\n\nВ предложении укажите цену за единицу без НДС, стоимость доставки на объект, срок поставки и доступный объём. Если предлагаете аналог, приложите паспорт и опишите отличия от спецификации.\n\nОтвет ждём до {срок}.\n\n{подпись}",
};

/** Шаблоны для мастера: свои, если они есть, иначе встроенный */
export function rfqTemplates(loaded: EmailTemplate[]): EmailTemplate[] {
  return loaded.length ? loaded : [DEFAULT_RFQ_TEMPLATE];
}
