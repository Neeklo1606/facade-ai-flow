/** Утверждение считается проверенным, только если у него есть источник */
export function isVerified(claim: Claim): boolean {
  return (claim.sources?.length ?? 0) > 0;
}

/** Все источники сравнения — для сноски в документе показа */
export function allSources(): Source[] {
  const seen = new Map<string, Source>();
  for (const alternative of ALTERNATIVES) {
    for (const claim of Object.values(alternative.claims)) {
      for (const source of claim.sources ?? []) seen.set(source.url, source);
    }
  }
  return [...seen.values()];
}
