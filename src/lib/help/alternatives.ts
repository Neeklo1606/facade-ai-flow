/**
 * Сравнение с системами, которые называют на встречах (ADR-020).
 *
 * Правило одно: утверждение о чужой системе либо имеет ссылку на открытый источник с датой
 * обращения, либо помечено словами «не проверено». Третьего состояния нет — это проверяется
 * тестом. Продукт требует источник у каждой своей цифры; требовать его у утверждения о соседе —
 * та же честность.
 *
 * И второе: мы говорим о том, что заявлено в открытом описании системы, а не о том, что в ней
 * есть. «В перечне модулей на сайте закупки не заявлены» проверяется за минуту и остаётся верным;
 * «в системе нет закупок» — догадка, за которую на встрече стыдно.
 */

export interface Source {
  /** Как назвать источник в сноске */
  title: string;
  url: string;
  /** Дата обращения: по ней видно, когда сравнение пора перепроверить */
  seen: string;
}

export interface Claim {
  text: string;
  source?: Source;
}

