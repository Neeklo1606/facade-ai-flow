import type { EmployeeRole } from "@/contracts";

/**
 * Справка (ADR-019). Статьи — по задачам человека, а не по экранам: он ищет «как принять
 * поставку», а не «экран поставок». Каждая статья отвечает на четыре вопроса в одном порядке:
 * зачем это нужно, шаги, что проверить после, куда идти дальше.
 *
 * Ссылки ведут на живой экран, а не на снимок: снимок устаревает в день выпуска.
 */

export interface HelpStep {
  /** Что сделать: одно действие, с названием того, что нажать */
  text: string;
  /** Куда это сделать: адрес экрана демонстрации, если шаг начинается с перехода */
  to?: string;
}

export interface HelpArticle {
  id: string;
  title: string;
  /** Зачем это нужно — одна строка */
  goal: string;
  /** Кому в первую очередь: список ролей из матрицы прав (ADR-012) */
  roles: EmployeeRole[];
  steps: HelpStep[];
  /** Что проверить после: как понять, что получилось */
  check: string;
  /** Куда дальше: следующий шаг работы */
  next: string;
  /** Экран, к которому статья относится: по нему подсказка в шапке находит статью */
  screen?: string;
  /** Слова, по которым статью ищут, но которых нет в тексте */
  keywords?: string[];
  /** К статье прикладывается таблица сравнения с другими системами (ADR-020) */
  compare?: true;
}

