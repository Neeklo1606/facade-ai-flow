/** Статья, которая учит работать с этим экраном; null — общей статьи для экрана нет */
export function articleForScreen(screenKey: string): HelpArticle | null {
  return helpArticles.find((article) => article.screen === screenKey) ?? null;
}

/** Поиск по заголовку, цели, шагам и ключевым словам */
export function searchHelp(query: string): HelpArticle[] {
  const text = query.trim().toLowerCase();
  if (!text) return helpArticles;
  return helpArticles.filter((article) =>
    [
      article.title,
      article.goal,
      article.check,
      article.next,
      ...article.steps.map((step) => step.text),
      ...(article.keywords ?? []),
    ]
      .join(" ")
      .toLowerCase()
      .includes(text),
  );
}

/** Статьи роли — первыми: человеку сначала его работа, потом остальное */
export function sortForRole(articles: HelpArticle[], role: EmployeeRole | null): HelpArticle[] {
  if (!role) return articles;
  return [...articles].sort(
    (a, b) => Number(b.roles.includes(role)) - Number(a.roles.includes(role)),
  );
}
