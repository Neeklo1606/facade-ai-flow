export type DemoOnlyId = keyof typeof DEMO_ONLY_NOTES;

/** Текст пометки для текущего контура */
export function note(id: PromiseId, contour: Contour = dataSource as Contour): string {
  return PROMISE_NOTES[id][contour === "server" ? "server" : "demo"];
}

/** Текст пометки, которая существует только в демонстрации; в рабочем контуре — пусто */
export function demoOnly(id: DemoOnlyId, contour: Contour = dataSource as Contour): string {
  return contour === "demo" ? DEMO_ONLY_NOTES[id].text : "";
}
