export type PromiseId = keyof typeof PROMISE_NOTES;

/**
 * Подпись действия загрузки документа. В демонстрации файл «разбирают» (стадии проводит
 * симулятор), в рабочем контуре — только кладут в реестр, и кнопка не должна обещать разбор.
 */
export function uploadActionLabel(contour: Contour = dataSource as Contour): string {
  return contour === "demo" ? "Загрузить и разобрать" : "Загрузить в реестр";
}

/**
 * Извлекаются ли позиции из загруженного файла. В демонстрации это делает симулятор,
 * в рабочем контуре — никто: обработчика разбора пока нет (аудит соответствия, п. 2).
 *
 * Экраны спрашивают здесь, а не у `dataSource`: пометка и поведение обязаны ехать вместе.
 * Пока эта функция отвечает «нет», экран проверки не может говорить «документ обрабатывается»
 * — обрабатывать его некому, и ожидание не кончится.
 */
export function extractsDocuments(contour: Contour = dataSource as Contour): boolean {
  return contour === "demo";
}

