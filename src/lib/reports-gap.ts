/**
 * Вид работ, последний факт по захватке и «бригады без отчёта» считаются по отчётам с площадки.
 * Когда отчётов нет на руках, такие значения не показываются вовсе: посчитанные по пустому
 * списку, они соврали бы — «бригад без отчёта: 2» при пяти пришедших отчётах.
 *
 * Причин ровно две, и они говорятся разными словами: раздел закрыт роли (ADR-012) или запрос
 * не прошёл. Молчать нельзя — «—» без причины читается как «данных нет».
 */
export type ReportsGap = "closed" | "failed";

/** Подпись под значением, которое не показано */
export const reportsGapNote: Record<ReportsGap, string> = {
  closed: "Отчёты с площадки закрыты вашей роли",
  failed: "Отчёты с площадки не загрузились",
};

/** Строка вида «Вид работ — из отчётов с площадки, раздел закрыт вашей роли» */
export function reportsGapLine(subject: string, gap: ReportsGap): string {
  return gap === "closed"
    ? `${subject} — из отчётов с площадки, раздел закрыт вашей роли`
    : `${subject} — из отчётов с площадки, они не загрузились`;
}
