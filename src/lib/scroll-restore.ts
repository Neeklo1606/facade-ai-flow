/**
 * Восстановление прокрутки роутера без прыжка наверх после загрузки (ADR-068).
 *
 * TanStack Router при первой отрисовке после гидратации прокручивает окно в начало. Если
 * человек уже успел пролистать страницу и коснуться плитки, страница прыгает вверх,
 * а касание приходится мимо ссылки. Первая отрисовка с уже прокрученным окном сброс
 * пропускает. При перезагрузке окно в этот момент ещё в начале, и сохранённая позиция
 * восстанавливается как раньше. Остальные переходы работают без изменений.
 */
export function keepEarlyScroll(
  scrolled: () => boolean = () =>
    typeof window !== "undefined" && (window.scrollY > 0 || window.scrollX > 0),
): () => boolean {
  let first = true;
  return () => {
    if (!first) return true;
    first = false;
    return !scrolled();
  };
}
