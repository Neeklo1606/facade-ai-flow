export const ARTICLE_SLUGS = ARTICLES.map((article) => article.slug);

export const articleBySlug = (slug: string) => ARTICLES.find((item) => item.slug === slug);

/** Минуты чтения: 180 слов в минуту, не меньше одной */
export function readingMinutes(article: Article): number {
  const words = article.body
    .flatMap((block) => (block.kind === "list" ? block.items : [block.text]))
    .concat(article.lead)
    .join(" ")
    .split(/\s+/).length;
  return Math.max(1, Math.round(words / 180));
}
