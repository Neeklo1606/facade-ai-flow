function info(key: keyof typeof screens): ScreenInfo {
  return { key, ...screens[key] };
}

/** Экран по адресу. `search` — строка запроса или объект параметров маршрута */
export function screenFor(
  pathname: string,
  search: string | Record<string, unknown> = "",
): ScreenInfo {
  const params =
    typeof search === "string"
      ? new URLSearchParams(search)
      : new URLSearchParams(
          Object.entries(search).flatMap(([k, v]) => (v == null ? [] : [[k, String(v)]])),
        );
  const path = pathname.replace(/\/+$/, "") || "/";

  if (path === "/") return info("dashboard");
  if (path === "/projects") return info("projects");
  if (path === "/agent") return info("agent");
  if (path === "/access") return info("access");
  if (path === "/catalogs") return info("catalogs");
  if (path === "/demo-stats") return info("demo-stats");

  const inProject = path.match(/^\/projects\/[^/]+(?:\/([^/]+)(?:\/([^/]+))?)?$/);
  if (inProject) {
    const [, section, child] = inProject;
    if (!section) {
      const tab = params.get("tab");
      if (tab === "progress") return info("project-progress");
      if (tab === "team") return info("project-team");
      return info("project");
    }
    if (section === "documents") return info(child ? "document" : "documents");
    if (section === "materials") return info("materials");
    if (section === "procurement") {
      if (child) return info("rfq");
      return info(params.get("view") === "suppliers" ? "suppliers" : "procurement");
    }
    if (section === "deliveries") return info("deliveries");
    if (section === "field-reports") return info("field-reports");
    if (section === "timeline") return info("timeline");
  }

  const planned = plannedSections[path.slice(1)];
  if (planned) {
    return {
      key: "section",
      name: planned,
      help: [
        `Раздела «${planned}» пока нет: экран описывает, что в нём будет.`,
        "Отвечает на вопрос, когда появится раздел и где эти данные можно посмотреть сейчас.",
        "Перейдите по ссылке на экране в раздел, который уже работает.",
      ],
    };
  }

  return {
    key: "not-found",
    name: "Раздел не найден",
    help: [
      "Такого адреса в системе нет.",
      "Скорее всего, ссылка устарела или в адресе опечатка.",
      "Вернитесь к списку объектов и откройте нужный раздел из меню.",
    ],
  };
}
